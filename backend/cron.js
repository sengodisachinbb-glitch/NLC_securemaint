// NLC-SecureMaint Automated Background Scheduler
// Handles PM auto-generation and SLA escalation every minute using node-cron

require("dotenv").config();
const cron = require("node-cron");
const db = require("./db");
const { logAudit } = require("./audit");

/**
 * Checks whether demo mode is active.
 * When DEMO_MODE=true, interval_days are treated as minutes so you can demonstrate it live.
 */
const isDemoMode = () => process.env.DEMO_MODE === "true";

/**
 * Computes next due date/time based on interval and DEMO_MODE setting.
 */
const calculateNextDue = (intervalDays, fromDate = new Date()) => {
  const baseTime = fromDate instanceof Date ? fromDate.getTime() : new Date(fromDate).getTime();
  const intervalMs = isDemoMode()
    ? Number(intervalDays) * 60 * 1000               // Demo Mode: minutes
    : Number(intervalDays) * 24 * 60 * 60 * 1000;    // Standard Mode: days

  return new Date(baseTime + intervalMs).toISOString();
};

/**
 * Core Scheduler Logic:
 * 1. Generates preventive work orders for schedules due on or before now (if no open order exists).
 * 2. Escalates work orders that have passed their sla_due_at and are not yet completed/closed.
 */
const runPmScheduler = () => {
  const nowIso = new Date().toISOString();

  // -------------------------------------------------------------
  // Part 1: Auto-generate Preventive Maintenance Work Orders
  // -------------------------------------------------------------
  try {
    const dueSchedules = db.prepare("SELECT * FROM pm_schedules WHERE next_due <= ?").all(nowIso);

    for (const schedule of dueSchedules) {
      // Check if there is already an open preventive work order for this equipment
      const openOrder = db.prepare(`
        SELECT id FROM work_orders
        WHERE equipment_id = ?
          AND type = 'preventive'
          AND status NOT IN ('Closed', 'Rejected')
      `).get(schedule.equipment_id);

      if (!openOrder) {
        // Fetch equipment information for title
        const eq = db.prepare("SELECT code, name FROM equipment WHERE id = ?").get(schedule.equipment_id);
        const eqCode = eq ? eq.code : `EQ-${schedule.equipment_id}`;
        const title = `[PM] ${schedule.task} (${eqCode})`;
        const description = `Automated preventive maintenance generated by system schedule #${schedule.id}. Interval: ${schedule.interval_days} ${isDemoMode() ? "minute(s)" : "day(s)"}.`;

        // Default requester to Admin user (ID 1)
        const adminUser = db.prepare("SELECT id FROM users WHERE role = 'Admin' LIMIT 1").get();
        const requesterId = adminUser ? adminUser.id : 1;

        // Advance schedule's next_due
        const nextDue = calculateNextDue(schedule.interval_days);

        // Insert new preventive work order
        const insertStmt = db.prepare(`
          INSERT INTO work_orders (title, description, equipment_id, requester_id, priority, status, type)
          VALUES (?, ?, ?, ?, 'Medium', 'Submitted', 'preventive')
        `);
        const result = insertStmt.run(title, description, schedule.equipment_id, requesterId);

        // Update PM schedule with new next_due and timestamp
        db.prepare("UPDATE pm_schedules SET next_due = ?, last_done = ? WHERE id = ?").run(
          nextDue,
          nowIso,
          schedule.id
        );

        // Log audit trail
        logAudit(null, "PM_AUTO_GENERATED", "work_orders", {
          schedule_id: schedule.id,
          work_order_id: result.lastInsertRowid,
          equipment_id: schedule.equipment_id,
          task: schedule.task,
          next_due: nextDue
        });

        console.log(`[Cron] Generated PM Work Order #${result.lastInsertRowid} for schedule #${schedule.id}`);
      }
    }
  } catch (err) {
    console.error("[Cron] Error during PM schedule check:", err);
  }

  // -------------------------------------------------------------
  // Part 2: Check & Escalate Overdue SLA Work Orders
  // -------------------------------------------------------------
  escalateOverdueOrders();
};

/**
 * Checks and escalates overdue work orders whose sla_due_at has passed
 * and whose status is still active (not Completed, Closed, or Rejected).
 * Exported so it can be called directly by tests, on-demand jobs, or routes.
 */
const escalateOverdueOrders = () => {
  const nowIso = new Date().toISOString();
  try {
    const overdueOrders = db.prepare(`
      SELECT id, title, sla_due_at, status
      FROM work_orders
      WHERE sla_due_at IS NOT NULL
        AND sla_due_at <= ?
        AND status NOT IN ('Completed', 'Closed', 'Rejected')
        AND (escalated = 0 OR escalated IS NULL)
    `).all(nowIso);

    for (const order of overdueOrders) {
      db.prepare("UPDATE work_orders SET escalated = 1, updated_at = ? WHERE id = ?").run(nowIso, order.id);

      logAudit(null, "WORK_ORDER_ESCALATED", "work_orders", {
        id: order.id,
        title: order.title,
        sla_due_at: order.sla_due_at,
        status: order.status
      });

      console.log(`[Cron] Escalated overdue work order #${order.id} (SLA: ${order.sla_due_at})`);
    }

    return overdueOrders;
  } catch (err) {
    console.error("[Cron] Error during SLA escalation check:", err);
    return [];
  }
};

/**
 * Initializes the node-cron runner every minute (* * * * *)
 */
const initCronJobs = () => {
  // Run on startup once immediately to process any pending due items
  runPmScheduler();

  // Schedule to run every minute
  cron.schedule("* * * * *", () => {
    runPmScheduler();
  });

  console.log(`[Cron] Scheduler initialized (running every minute. DEMO_MODE=${isDemoMode()})`);
};

module.exports = {
  initCronJobs,
  runPmScheduler,
  escalateOverdueOrders,
  calculateNextDue,
  isDemoMode
};
